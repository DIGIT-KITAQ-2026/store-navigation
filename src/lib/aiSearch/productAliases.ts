/**
 * 別名として扱う最小文字数。1文字だと無関係な検索語にほぼ必ず当たってしまう
 * (「茶」「皿」のような1文字の別名は、検索語に含まれるかの向きでは使わない)。
 */
const MIN_ALIAS_LENGTH_FOR_CONTAINMENT = 2;

/** 正規化済みの別名。毎回作り直すと無駄なので1度だけ作る */
const normalizedAliases = new Map<string, string[]>(
  Object.entries(PRODUCT_ALIASES).map(([name, aliases]) => [
    normalizeSearchText(name),
    aliases.map(normalizeSearchText),
  ])
);

/**
 * その商品が、検索語で指されているか(商品名そのものに一致したのと同じ扱いにしてよいか)。
 *
 * 検索語はここで正規化する。呼び出し側が正規化済みの値を渡しても結果は変わらない
 * (正規化は2回かけても同じ)。正規化前の値を渡されて静かに外れるのを防ぐため。
 */
export function matchesAlias(productName: string, query: string): boolean {
  const aliases = normalizedAliases.get(normalizeSearchText(productName));
  const normalizedQuery = normalizeSearchText(query);
  if (!aliases || normalizedQuery.length === 0) return false;

  return aliases.some(
    (alias) =>
      alias === normalizedQuery ||
      alias.includes(normalizedQuery) ||
      (alias.length >= MIN_ALIAS_LENGTH_FOR_CONTAINMENT && normalizedQuery.includes(alias))
  );
}
