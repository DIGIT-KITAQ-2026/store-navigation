/** 異体字セレクタ(U+FE0F など)を除いて比較できるようにする */
function normalizeEmoji(text: string): string {
  return text.replace(/[\uFE0E\uFE0F]/g, "");
}

/** 長い絵文字から先に置き換えたいので、文字数の多い順に並べておく */
const EMOJI_ENTRIES: [string, string][] = Object.entries(EMOJI_QUERIES)
  .map(([emoji, query]): [string, string] => [normalizeEmoji(emoji), query])
  .sort((a, b) => b[0].length - a[0].length);

/**
 * 検索語の中の絵文字を日本語に置き換える。絵文字が無ければそのまま返す。
 * 「😷」→「マスク」、「😷が欲しい」→「マスク が欲しい」のように部分的にも効く。
 */
export function expandEmojiQuery(query: string): string {
  let replaced = normalizeEmoji(query);
  let changed = false;

  for (const [emoji, term] of EMOJI_ENTRIES) {
    if (!replaced.includes(emoji)) continue;
    replaced = replaced.split(emoji).join(` ${term} `);
    changed = true;
  }
  if (!changed) return query;

  return replaced.replace(/\s+/g, " ").trim() || query;
}
