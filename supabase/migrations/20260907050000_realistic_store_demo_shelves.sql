-- 新100均想定3D店舗(PR #31)向けのデモ商品投入に先立ち、既存店舗内へ物理棚(shelves)を
-- 40個(Shelf_01〜Shelf_08、各5棚)追加する。
--
-- 背景: products.shelf_idはshelvesテーブルの個々の物理棚UUIDを参照し、かつUNIQUE制約が
-- あるため「1物理棚につき1商品」までしか登録できない。既存の物理棚は各Shelf_01〜08に
-- 3棚ずつ(計24棚)しか無く、空きは実質1棚のみだったため、新カテゴリ8種に各5商品程度の
-- デモ商品を登録するには物理棚が不足していた。
--
-- このMigrationは新しい物理棚を追加するだけで、以下は一切行わない:
-- - 既存のshelves/products/shelf_locationsの削除・変更
-- - 新規stores行の作成(検索・管理者APIが「店舗は1件のみ」という前提のため、既存の
--   唯一の店舗のまま棚だけを増やす)
-- - shelf_locations.location_code・categories.codeの変更
-- - unity_position_x/y/zへの新3D(GLB)座標の書き込み(新3D側はShelf_01〜08の文字列だけを
--   受け取り、座標変換はフロントエンドで行うため、ここでは触れない。デフォルト値0.0のまま)
--
-- 商品登録自体(products行の作成)はこのMigrationでは行わない。実際の管理者API
-- (/api/admin/product-registration)を、既存のテスト管理者アカウントで認証した上で
-- 呼び出す形で別途行う(実運用と同じ認証・RLS・カテゴリ整合性チェックの経路を検証するため)。
--
-- バーコード採番: 実在バーコードとの衝突を避けるため、既存デモ棚(4909で始まる別の桁構成)
-- とは異なる専用プレフィックス`49090990`(8桁)+ 5桁連番(00001〜00040)を使う。
-- 連番はカテゴリ順(Shelf_01→00001-00005、Shelf_02→00006-00010、…Shelf_08→00036-00040)。

