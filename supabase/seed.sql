-- 複数の物理棚(shelves、商品バーコード登録用)を紐付けられる。
--
-- 棚(shelves)バーコードの採番規則(EAN-13、13桁): 490(JAN日本国コード) + 9(棚固定) +
-- ゾーン番号2桁(Shelf_01〜08の数字部分) + ゾーン内枝番2桁(01〜03) + 0000(予備) +
-- チェックデジット1桁。桁4を9にすることで商品バーコード(桁4が1)と数字空間が衝突しない。
-- 詳細・対応表は docs/データベース設計.md 参照。

